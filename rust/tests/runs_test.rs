use sikaru::prelude::*;

mod wire_test_utils;

#[tokio::test]
#[allow(unused_variables, unreachable_code)]
async fn test_runs_start_with_wiremock() {
    wire_test_utils::reset_wiremock_requests().await.unwrap();
    let wiremock_base_url = wire_test_utils::get_wiremock_base_url();

    let mut config = ClientConfig {
        token: Some("<token>".to_string()),
        ..Default::default()
    };
    config.base_url = wiremock_base_url.to_string();
    let client = Sikaru::new(config).expect("Failed to build client");

    let result = client
        .runs
        .start(
            &"project_id".to_string(),
            &"harness_id".to_string(),
            &StartHarnessRunRequest {
                input: HashMap::from([("key".to_string(), serde_json::json!("value"))]),
                policy: HashMap::from([("key".to_string(), serde_json::json!("value"))]),
                product_context: HashMap::from([("key".to_string(), serde_json::json!("value"))]),
                tenant_id: "tenant_id".to_string(),
                user_id: "user_id".to_string(),
                auto_improve: None,
                capability_grants: None,
                compute_provider_id: None,
                conversation_id: None,
                correlation_id: None,
                event_delivery: None,
                execution_environment: None,
                job_id: None,
                model: None,
                run_mode: None,
                tool_provider_refs: None,
                trace_id: None,
            },
            None,
        )
        .await;

    assert!(result.is_ok(), "Client method call should succeed");

    wire_test_utils::verify_request_count(
        "POST",
        "/v1/projects/project_id/harnesses/harness_id/runs",
        None,
        1,
    )
    .await
    .unwrap();
}

